"""Generate a URDF (UR5 + OnRobot RG2 + wrist depth camera) from the config.

The joint origins are built directly from the DH table, so the URDF and
`UR5Kinematics` agree exactly (the IK used by the Isaac backend is the same
code as in the simple backend). Collision / visual shapes are simplified
cylinders and boxes; link masses come from ur_description. Each DH frame i is
the child frame of joint i, so the URDF chain reads

    joint_1 (origin = identity, axis z)
    joint_k (origin = Tz(d_{k-1}) Tx(a_{k-1}) Rx(alpha_{k-1}), axis z),  k = 2..6
    flange  (fixed, origin = Tz(d_6) Tx(a_6) Rx(alpha_6))
    tcp     (fixed, z = tcp_offset)   -> fingers (prismatic, along TCP x)
"""

from __future__ import annotations

import numpy as np

ARM_JOINTS = [f"joint_{i}" for i in range(1, 7)]
FINGER_JOINTS = ["finger_left_joint", "finger_right_joint"]


def _inertia_cyl(m, r, h):
    ixx = m * (3 * r * r + h * h) / 12.0
    return ixx, ixx, 0.5 * m * r * r


def _inertial(m, xyz=(0, 0, 0), rpy=(0, 0, 0), I=None):
    ixx, iyy, izz = I if I else (1e-4, 1e-4, 1e-4)
    return (f'    <inertial><origin xyz="{_v(xyz)}" rpy="{_v(rpy)}"/><mass value="{m:.4f}"/>'
            f'<inertia ixx="{ixx:.6f}" ixy="0" ixz="0" iyy="{iyy:.6f}" iyz="0" izz="{izz:.6f}"/>'
            f'</inertial>\n')


def _v(x):
    return " ".join(f"{float(a):.6f}" for a in x)


def _geom(shape, xyz, rpy, color=None, collision=True):
    s = ""
    mat = f'<material name="{color[0]}"><color rgba="{color[1]}"/></material>' if color else ""
    s += f'    <visual><origin xyz="{_v(xyz)}" rpy="{_v(rpy)}"/><geometry>{shape}</geometry>{mat}</visual>\n'
    if collision:
        s += f'    <collision><origin xyz="{_v(xyz)}" rpy="{_v(rpy)}"/><geometry>{shape}</geometry></collision>\n'
    return s


def _cyl_between(p0, p1, r):
    """Cylinder geometry from p0 to p1 (both in the link frame)."""
    p0, p1 = np.asarray(p0, float), np.asarray(p1, float)
    d = p1 - p0
    L = float(np.linalg.norm(d))
    if L < 1e-6:
        return None
    z = d / L
    pitch = np.arccos(np.clip(z[2], -1, 1))
    yaw = np.arctan2(z[1], z[0])
    return f'<cylinder radius="{r}" length="{L:.6f}"/>', (p0 + p1) / 2, (0.0, pitch, yaw)


def generate_urdf(cfg) -> str:
    dh = cfg.robot.dh
    d, a, alpha = (np.asarray(dh[k], float) for k in ("d", "a", "alpha"))
    masses = list(cfg.robot.link_masses)
    lim = cfg.robot.joint_limits
    g = cfg.gripper
    cam = cfg.camera
    grey = ("ur_grey", "0.75 0.77 0.80 1")
    blue = ("ur_blue", "0.35 0.55 0.75 1")
    dark = ("rg2_dark", "0.15 0.15 0.15 1")
    radii = [0.06, 0.054, 0.045, 0.04, 0.04, 0.035]

    out = ['<?xml version="1.0"?>',
           "<!-- generated by grasp_rl/urdf.py from configs/*.yaml - do not edit by hand -->",
           '<robot name="ur5_rg2">',
           '  <link name="base_link">',
           _inertial(4.0, (0, 0, 0.03), I=_inertia_cyl(4.0, 0.075, 0.06)) +
           _geom('<cylinder radius="0.075" length="0.058"/>', (0, 0, 0.031), (0, 0, 0), blue),
           "  </link>"]
    parent = "base_link"
    for i in range(6):
        link = f"link_{i + 1}"
        # geometry of link i+1 lives in DH frame i+1's *pre-offset* frame, i.e. the
        # joint's child frame; it spans the offset Tz(d) Tx(a) to the next joint.
        body = ""
        segs = []
        if abs(d[i]) > 1e-6:
            # link_1 starts above the base so it never touches the table top (z = 0)
            z0 = min(0.065, 0.7 * d[i]) if i == 0 else 0.0
            segs.append(((0, 0, z0), (0, 0, d[i])))
        if abs(a[i]) > 1e-6:
            segs.append(((0, 0, d[i]), (a[i], 0, d[i])))
        if not segs:
            segs.append(((0, 0, -0.03), (0, 0, 0.03)))
        for p0, p1 in segs:
            res = _cyl_between(p0, p1, radii[i])
            if res:
                shape, mid, rpy = res
                body += _geom(shape, mid, rpy, grey if i in (1, 2) else blue)
        com = np.mean([np.add(p0, p1) / 2 for p0, p1 in segs], axis=0)
        L = sum(np.linalg.norm(np.subtract(p1, p0)) for p0, p1 in segs)
        out.append(f'  <link name="{link}">')
        out.append(_inertial(masses[i], com, I=_inertia_cyl(masses[i], radii[i], max(L, 0.05))) + body)
        out.append("  </link>")
        if i == 0:
            xyz, rpy = (0, 0, 0), (0, 0, 0)
        else:
            xyz, rpy = (a[i - 1], 0, d[i - 1]), (alpha[i - 1], 0, 0)
        out.append(f'  <joint name="joint_{i + 1}" type="revolute">'
                   f'<parent link="{parent}"/><child link="{link}"/>'
                   f'<origin xyz="{_v(xyz)}" rpy="{_v(rpy)}"/><axis xyz="0 0 1"/>'
                   f'<limit lower="{lim[i][0]}" upper="{lim[i][1]}" effort="150" '
                   f'velocity="{cfg.robot.max_joint_speed}"/><dynamics damping="0.0" friction="0.0"/></joint>')
        parent = link

    # flange (DH frame 6) ------------------------------------------------
    out.append('  <link name="flange">' + "\n" + _inertial(0.01) + "  </link>")
    out.append(f'  <joint name="flange_fixed" type="fixed"><parent link="link_6"/><child link="flange"/>'
               f'<origin xyz="{_v((a[5], 0, d[5]))}" rpy="{_v((alpha[5], 0, 0))}"/></joint>')

    # RG2 body: from flange down to the top of the fingers --------------
    tcp = float(g.tcp_offset)
    body_len = tcp - float(g.finger_length)
    bx, by = g.body_footprint
    out.append('  <link name="rg2_body">')
    out.append(_inertial(float(g.mass) - 0.1, (0, 0, body_len / 2)) +
               _geom(f'<box size="{bx} {by} {body_len:.4f}"/>', (0, 0, body_len / 2), (0, 0, 0), dark))
    out.append("  </link>")
    out.append('  <joint name="rg2_mount" type="fixed"><parent link="flange"/><child link="rg2_body"/>'
               '<origin xyz="0 0 0" rpy="0 0 0"/></joint>')

    # TCP: centre between the fingertips, z along the approach direction ------
    out.append('  <link name="tcp">' + "\n" + _inertial(0.001) + "  </link>")
    out.append(f'  <joint name="tcp_fixed" type="fixed"><parent link="flange"/><child link="tcp"/>'
               f'<origin xyz="0 0 {tcp:.6f}" rpy="0 0 0"/></joint>')

    # fingers: prismatic along TCP x, joint value = half opening -----------
    t, w, fl = float(g.finger_thickness), float(g.finger_width), float(g.finger_length)
    half_stroke = float(g.stroke) / 2
    for name, sign in (("finger_left", 1), ("finger_right", -1)):
        out.append(f'  <link name="{name}">')
        out.append(_inertial(0.05, (sign * t / 2, 0, -fl / 2)) +
                   _geom(f'<box size="{t} {w} {fl}"/>', (sign * t / 2, 0, -fl / 2), (0, 0, 0), dark))
        out.append("  </link>")
        out.append(f'  <joint name="{name}_joint" type="prismatic"><parent link="tcp"/>'
                   f'<child link="{name}"/><origin xyz="0 0 0" rpy="0 0 0"/>'
                   f'<axis xyz="{sign} 0 0"/>'
                   f'<limit lower="0" upper="{half_stroke:.4f}" effort="{float(g.force):.1f}" velocity="0.13"/>'
                   f'</joint>')

    # wrist camera (ROS optical frame: z forward) ---------------------------
    tilt = np.deg2rad(float(cam.tilt_deg))
    out.append('  <link name="camera_link">' + "\n" + _inertial(0.06) +
               _geom('<box size="0.042 0.042 0.023"/>', (0, 0, -0.012), (0, 0, 0),
                     ("cam", "0.2 0.2 0.25 1"), collision=False) + "  </link>")
    out.append(f'  <joint name="camera_fixed" type="fixed"><parent link="tcp"/><child link="camera_link"/>'
               f'<origin xyz="{_v(cam.mount_xyz)}" rpy="{tilt:.6f} 0 0"/></joint>')
    out.append("</robot>")
    return "\n".join(out) + "\n"


def write_urdf(cfg, path):
    with open(path, "w") as f:
        f.write(generate_urdf(cfg))
    return path
